import 'package:flutter/foundation.dart';
import '../models/order.dart';
import 'package:cloud_firestore/cloud_firestore.dart' as firestore;
import '../services/database/order_firestore.dart';

class OrderProvider extends ChangeNotifier {
  final OrderFirestore _orderFirestore = OrderFirestore();

  /// Local state
  bool _isLoading = false;
  bool get isLoading => _isLoading;

  String? _errorMessage;
  String? get errorMessage => _errorMessage;

  // Dishes of the currently selected restaurant
  List<Order> _userOrders = [];
  List<Order> get userOrders => _userOrders;

  /// Clears all errors
  void clearErrors({bool clearData = false}) {
    _errorMessage = null;
    notifyListeners();
  }

  // Recovers an order from the local list by its ID
  Order? getOrderById(String orderId) {
    try {
      return _userOrders.firstWhere((order) => order.id == orderId);
    } catch (e) {
      return null;
    }
  }

  /// Depending on the (restaurantId, pickupDateTime) tuple:
  /// - adds a dish to an existing order
  /// - creates a new order
  Future<void> addOrder({
    required String userId,
    required String restaurantId,
    required String restaurantName,
    required String restaurantAddress,
    required firestore.GeoPoint restaurantLocation,
    required String dishId,
    required String dishName,
    required double dishPrice,
    required DateTime pickupDateTime,
  }) async {
    try {
      _isLoading = true;
      clearErrors();
      notifyListeners();

      // Updates the local list of orders for the user
      await fetchUserOrders(userId);

      int? orderIndex = await hasPendingOrderDateTime(restaurantId, pickupDateTime);

      if (orderIndex != null) {
        // If an order already exists for the restaurant and date, add the dish to that order
        Order existingOrder = _userOrders[orderIndex];

        // Check if the dish is already in the order
        OrderItem? existingDish;
        try {
          existingDish = existingOrder.dishes.firstWhere(
            (item) => item.dishId == dishId,
          );
        } catch (e) {
          existingDish = null;
        }

        if (existingDish != null) {
          // If the dish is already in the order, increase its quantity
          existingOrder.copyWith(
              total: existingOrder.total + dishPrice,
              updatedDishes: {
                dishId: OrderItem(
                  dishId: existingDish.dishId,
                  name: existingDish.name,
                  quantity: existingDish.quantity + 1,
                  price: existingDish.price
                )
              }
          );
        } else {
          // If the dish is not in the order, add it
          existingOrder.dishes.add(OrderItem(
            dishId: dishId,
            name: dishName,
            quantity: 1, // Initial quantity
            price: dishPrice,
          ));

          // Update the total price of the order
          existingOrder.copyWith(total: existingOrder.total + dishPrice);
        }

      } else {
        // If no pending order exists, create a new one
        Order newOrder = Order(
          id: '', // ID will be generated by Firestore
          userId: userId,
          restaurantName: restaurantName,
          restaurantId: restaurantId,
          dateTime: pickupDateTime,
          status: 'pending',
          total: dishPrice, // Initial total with one dish
          restaurantAddress: restaurantAddress,
          restaurantLocation: restaurantLocation,
          dishes: [
            OrderItem(
              dishId: dishId,
              name: dishName,
              quantity: 1, // Initial quantity
              price: dishPrice,
            ),
          ],
        );
      }






      _isLoading = false;
      notifyListeners();
    } catch (e) {
      _isLoading = false;
      _errorMessage = 'Errore durante l\'aggiunta al carrello: $e';
      notifyListeners();
      debugPrint(_errorMessage);
    }
  }

  // Recupera tutti gli ordini dell'utente
  Future<void> fetchUserOrders(String userId) async {
    try {
      _isLoading = true;
      clearErrors();
      notifyListeners();

      _userOrders = await _orderFirestore.getUserOrders(userId);

      _isLoading = false;
      notifyListeners();
    } catch (e) {
      _isLoading = false;
      _errorMessage = 'Errore durante il recupero degli ordini: $e';
      notifyListeners();
      debugPrint(_errorMessage);
    }
  }



  // Aggiorna lo stato di un ordine
  Future<void> updateOrderStatus(String orderId, String status) async {
    try {
      _isLoading = true;
      clearErrors();
      notifyListeners();

      await _orderFirestore.updateOrderStatus(orderId, status);



      _isLoading = false;
      notifyListeners();
    } catch (e) {
      _isLoading = false;
      _errorMessage = 'Errore durante l\'aggiornamento dello stato dell\'ordine: $e';
      notifyListeners();
      debugPrint(_errorMessage);
    }
  }

  // Controlla se esiste un ordine in sospeso per un ristorante alla data di ritiro indicata
  Future<int?> hasPendingOrderDateTime(String restaurantId, DateTime pickupDateTime) async {
    try {
      // Prima controlla nella lista locale
      for (int i = 0; i < _userOrders.length; i++) {
        Order order = _userOrders[i];
        if (order.restaurantId == restaurantId &&
            order.status == 'pending' &&
            _isSameDateTime(order.dateTime, pickupDateTime)) {
          return i;  // Restituisce l'indice dell'ordine trovato
        }
      }

      // Se non è stato trovato nella lista locale, restituisci null
      return null;
    } catch (e) {
      debugPrint('Errore durante la verifica dell\'ordine in sospeso: $e');
      return null;
    }
  }

  // Helper method per confrontare le date ignorando i secondi e i millisecondi
  bool _isSameDateTime(DateTime date1, DateTime date2) {
    return date1.year == date2.year &&
           date1.month == date2.month &&
           date1.day == date2.day &&
           date1.hour == date2.hour &&
           date1.minute == date2.minute;
  }
}